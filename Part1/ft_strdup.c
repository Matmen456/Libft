#include "libft.h"

char	*ft_strdup(const char *s)
{
	size_t	i;
	char	*p;

	p = malloc(ft_strlen(s) + 1);
	if (p == NULL)
	{
		errno = ENOMEM;
		return (NULL);
	}
	i = 0;
	while (s[i])
	{
		p[i] = s[i];
		i++;
	}
	p[i] = '\0';
	return (p);
}
